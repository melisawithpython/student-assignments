# Kullanıcıdan iki sayı alır
sayi1 = float(input("1. sayıyı girin: "))
sayi2 = float(input("2. sayıyı girin: "))

# İşlemler ve sonuçların ekrana yazdırılması
print(f"Toplama: {sayi1 + sayi2}")
print(f"Çıkarma: {sayi1 - sayi2}")
print(f"Çarpma: {sayi1 * sayi2}")
print(f"Bölme: {sayi1 / sayi2}")
print(f"Mod alma: {sayi1 % sayi2}")
print(f"Üs alma: {sayi1 ** sayi2}")
